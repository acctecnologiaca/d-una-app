  /// Returns the list of 24 Venezuelan states/entities sorted alphabetically.
  static List<String> get states {
    final list = _data.keys.toList()..sort();
    return list;
  }

  /// Returns the list of cities for a given Venezuelan state.
  static List<String> getCities(String stateName) {
    if (stateName.trim().isEmpty) return [];

    // Exact match
    if (_data.containsKey(stateName)) {
      return List<String>.from(_data[stateName]!)..sort();
    }

    // Normalization / case-insensitive search
    final normalizedInput = _normalize(stateName);
    for (final entry in _data.entries) {
      if (_normalize(entry.key) == normalizedInput) {
        return List<String>.from(entry.value)..sort();
      }
    }

    // Known aliases (e.g. Capital District, Vargas, etc.)
    if (normalizedInput == 'capital district' || normalizedInput == 'caracas') {
      return List<String>.from(_data['Distrito Capital']!)..sort();
    }
    if (normalizedInput == 'vargas') {
      return List<String>.from(_data['La Guaira']!)..sort();
    }

    return [];
  }

  /// Checks if a state belongs to Venezuela.
  static bool hasState(String stateName) {
    final normalizedInput = _normalize(stateName);
    for (final key in _data.keys) {
      if (_normalize(key) == normalizedInput) return true;
    }
    return normalizedInput == 'capital district' || normalizedInput == 'vargas';
  }

  static String _normalize(String text) {
    return text
        .toLowerCase()
        .replaceAll('á', 'a')
        .replaceAll('é', 'e')
        .replaceAll('í', 'i')
        .replaceAll('ó', 'o')
        .replaceAll('ú', 'u')
        .replaceAll('ñ', 'n')
        .trim();
  }
